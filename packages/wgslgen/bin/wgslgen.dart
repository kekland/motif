// ignore_for_file: avoid_print

import 'dart:convert';
import 'dart:io';

import 'package:wgslgen/wgslgen.dart';

Never printUsageAndExit() {
  print('Usage: wgslgen [.wgsl file] -o [output .dart file]');
  exit(1);
}

void main(List<String> args) {
  final outputIndex = args.indexOf('-o');
  if (outputIndex == -1 || outputIndex == args.length - 1) printUsageAndExit();

  final wgslgenRoot = Platform.script.resolve('../');
  final reflectScript = wgslgenRoot.resolve('tool/reflect.js');

  final inputFilePath = args[0];
  final inputFile = File(inputFilePath);

  final outputFilePath = args[outputIndex + 1];
  final outputFile = File(outputFilePath);

  if (!inputFile.existsSync()) {
    print('Error: Input file "${inputFile.path}" does not exist.');
    exit(1);
  }

  final reflectResult = Process.runSync(reflectScript.toFilePath(), ['-f', inputFile.path]);
  if (reflectResult.exitCode != 0) {
    print('Error reflecting "${inputFile.path}": ${reflectResult.stderr}');
    exit(1);
  }

  try {
    final reflectionJson = jsonDecode(reflectResult.stdout);
    final reflectionInfo = WgslReflectionInfo.fromJson(reflectionJson as Map<String, dynamic>);
    final outCode = <String>[
      '// GENERATED CODE - DO NOT MODIFY BY HAND',
      '//',
      '// Generated by wgslgen',
      '',
      'import \'dart:typed_data\';',
      'import \'package:wgpu/wgpu.dart\' as wgpu;',
      'import \'package:wgpu/wgsl.dart\' as wgsl;',
      '',
    ];

    outCode.addAll(generate(inputFile.uri.pathSegments.last, inputFile.readAsStringSync(), reflectionInfo));

    outputFile.writeAsStringSync(outCode.join('\n'));
  } catch (e, stack) {
    print('Error processing "${inputFile.path}": $e');
    print(stack);
    exit(1);
  }
}
